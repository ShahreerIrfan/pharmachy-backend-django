class RequirementsTraceabilityMatrix:
    """Versioned Traceability Matrix orchestrator and validator."""

    def __init__(self, requirements: list[RequirementTrace] | None = None):
        self.requirements: list[RequirementTrace] = requirements if requirements is not None else build_canonical_rtm()
        self._by_id: dict[str, RequirementTrace] = {r.req_id: r for r in self.requirements}

    def total_count(self) -> int:
        return len(self.requirements)

    def fr_count(self) -> int:
        return sum(1 for r in self.requirements if r.category == "FR")

    def nfr_count(self) -> int:
        return sum(1 for r in self.requirements if r.category == "NFR")

    def get(self, req_id: str) -> RequirementTrace | None:
        return self._by_id.get(req_id)

    def filter_by_context(self, context: str) -> list[RequirementTrace]:
        return [r for r in self.requirements if r.bounded_context == context]

    def filter_by_section(self, section: str) -> list[RequirementTrace]:
        return [r for r in self.requirements if r.section.startswith(section)]

    def get_all_mapped_endpoints(self) -> set[str]:
        endpoints = set()
        for r in self.requirements:
            endpoints.update(r.endpoints)
        return endpoints

    def get_unmapped_endpoints(self, canonical_catalog: set[str] | None = None) -> set[str]:
        catalog = canonical_catalog if canonical_catalog is not None else CANONICAL_REST_ENDPOINTS
        mapped = self.get_all_mapped_endpoints()
        return catalog - mapped

    def validate_integrity(self, canonical_catalog: set[str] | None = None) -> None:
        """
        Validates all RTM integrity invariants:
        1. Exact count: 82 FRs and 20 NFRs.
        2. Unique IDs.
        3. Zero orphan requirements.
        4. Zero unmapped endpoints.
        """
        if self.fr_count() != 82:
            raise ValueError(f"Integrity error: Expected 82 Functional Requirements, found {self.fr_count()}")
        if self.nfr_count() != 20:
            raise ValueError(f"Integrity error: Expected 20 Non-Functional Requirements, found {self.nfr_count()}")
        if len(self._by_id) != len(self.requirements):
            raise ValueError("Integrity error: Duplicate requirement IDs detected in matrix")

        for r in self.requirements:
            r.validate()

        unmapped = self.get_unmapped_endpoints(canonical_catalog)
        if unmapped:
            raise ValueError(f"Integrity error: Unmapped REST endpoints found: {sorted(list(unmapped))}")

    def export_dict(self) -> dict[str, Any]:
        return {
            "matrix_version": "2.0.0",
            "date": "2026-10-28",
            "srs_version": "SRS v2.0",
            "total_functional_requirements": self.fr_count(),
            "total_non_functional_requirements": self.nfr_count(),
            "zero_orphan_guarantee": True,
            "zero_unmapped_endpoints_guarantee": True,
            "requirements": [asdict(r) for r in self.requirements],
        }

    def export_json(self, filepath: str | None = None) -> str:
        data = self.export_dict()
        json_str = json.dumps(data, indent=2, ensure_ascii=False)
        if filepath:
            os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(json_str)
        return json_str

@dataclass(frozen=True)
class RequirementTrace:
    req_id: str
    title: str
    section: str
    priority: str  # 'M' (Must/Core MVP), 'S' (Should/Pilot), 'P' (Pro)
    category: str  # 'FR' or 'NFR'
    bounded_context: str
    models: list[str]
    endpoints: list[str]
    screens: list[str]
    permissions: list[str]
    test_targets: list[str]
    status: str = "APPROVED"

    def validate(self) -> None:
        if not self.req_id or not re.match(r"^(FR-\d{3}|NFR-\d{2})$", self.req_id):
            raise ValueError(f"Invalid requirement ID format: {self.req_id}")
        if not self.title.strip():
            raise ValueError(f"Requirement {self.req_id} must have a non-empty title")
        if not self.section.strip():
            raise ValueError(f"Requirement {self.req_id} must belong to a section")
        if self.category not in ("FR", "NFR"):
            raise ValueError(f"Requirement {self.req_id} category must be FR or NFR, got {self.category}")
        if self.priority not in ("M", "S", "P"):
            raise ValueError(f"Requirement {self.req_id} priority must be M, S, or P, got {self.priority}")
        if not self.bounded_context.strip():
            raise ValueError(f"Requirement {self.req_id} must declare a bounded context")
        if not self.models:
            raise ValueError(f"Requirement {self.req_id} has zero mapped models (orphan requirement)")
        if not self.endpoints:
            raise ValueError(f"Requirement {self.req_id} has zero mapped endpoints (orphan requirement)")
        if not self.screens:
            raise ValueError(f"Requirement {self.req_id} has zero mapped screens (orphan requirement)")
        if not self.permissions:
            raise ValueError(f"Requirement {self.req_id} has zero mapped permissions (orphan requirement)")
        if not self.test_targets:
            raise ValueError(f"Requirement {self.req_id} has zero mapped test targets (orphan requirement)")


